def wrap_line(text, max_width, font_size):
    if not text:
        return [""]
    out, cur = [], ""
    for ch in text:
        trial = cur + ch
        if pdfmetrics.stringWidth(trial, FONT, font_size) > max_width and cur:
            out.append(cur)
            cur = ch
        else:
            cur = trial
    out.append(cur)
    return out


def build():
    width, height = A4
    left_margin = 50
    right_margin = 50
    max_width = width - left_margin - right_margin
    header_y = height - 34
    top_y = height - 62
    bottom_limit = 46

    # 先排版为渲染行（含字号信息），再分页
    rendered = []
    for kind, text in CONTENT:
        if kind == "blank":
            rendered.append((FONT_SIZE, ""))
            continue
        size = {"h1": 16, "h2": 13, "h3": 11}.get(kind, FONT_SIZE)
        if kind in ("h1", "h2"):
            rendered.append((FONT_SIZE, ""))
        for seg in wrap_line(text, max_width, size):
            rendered.append((size, seg))
        if kind == "h1":
            rendered.append((FONT_SIZE, ""))

    pages = []
    page = []
    lines_used = 0
    for item in rendered:
        if lines_used >= LINES_PER_PAGE:
            pages.append(page)
            page = []
            lines_used = 0
        page.append(item)
        lines_used += 1
    if page:
        pages.append(page)

    total_pages = len(pages)
    out_path = os.path.join(OUT_DIR, f"{APP_NAME}_{VERSION}_软件说明书.pdf")
    c = canvas.Canvas(out_path, pagesize=A4)

    for i, page in enumerate(pages, 1):
        c.setFont(FONT, 9)
        c.drawString(left_margin, header_y, f"{APP_NAME} {VERSION}")
        c.drawRightString(width - right_margin, header_y, f"第 {i} 页 / 共 {total_pages} 页")
        c.setLineWidth(0.5)
        c.line(left_margin, header_y - 8, width - right_margin, header_y - 8)

        y = top_y
        for size, seg in page:
            c.setFont(FONT, size)
            if seg:
                c.drawString(left_margin, y, seg)
            y -= LEADING
        c.showPage()

    c.save()
    return out_path, total_pages, len(rendered)


if __name__ == "__main__":
    out, pages, total_lines = build()
    print("文件:", out)
    print("总页数:", pages)
    print("渲染行数:", total_lines)
    print("文件大小:", os.path.getsize(out), "字节")
    print("平均每页行数:", round(total_lines / pages, 1))
